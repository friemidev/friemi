export function getUnoCopy(locale: string, rulesetVersion: 1 | 2 = 2) {
  const key = locale === "zh-CN" ? "zh-CN" : locale === "fr" ? "fr" : "en";
  const copy = key === "zh-CN" ? zh : key === "fr" ? fr : en;
  return rulesetVersion === 1 ? { ...copy, ...legacyRules[key] } : copy;
}
export function unoCardUnit(count: number, locale: string) {
  if (count === 1 && locale !== "zh-CN") return locale === "fr" ? "carte" : "card";
  return getUnoCopy(locale).cards;
}
export function unoCardLabel(card: UnoCard, locale: string) {
  const t = getUnoCopy(locale);
  return `${card.color ? t[card.color] + " " : ""}${/^\d$/.test(card.value) ? card.value : t[card.value as "skip" | "reverse" | "draw2" | "wild" | "wild4"]}`;
}
export function unoErrorMessage(code: string, locale: string) {
  const t = getUnoCopy(locale);
  if (["SIGN_IN_REQUIRED", "UNAUTHORIZED"].includes(code)) return t.signIn;
  if (["ROOM_NOT_FOUND", "NOT_A_PLAYER", "NOT_A_MEMBER", "FORBIDDEN"].includes(code)) return t.missing;
  if (code === "ROOM_FULL") return t.full;
  if (["ROOM_STARTED", "GAME_STARTED", "ROOM_IN_PROGRESS"].includes(code)) return t.started;
  if (code === "LAST_CARD_MUST_BE_NUMBER") return t.lastNumber;
  if (code === "CARD_NOT_PLAYABLE") return t.notPlayable;
  if (code === "ONLY_DRAWN_CARD") return t.drawnOnly;
  if (["INVALID_REPORT", "DUPLICATE_REPORT"].includes(code)) return t.reportInvalid;
  if (code === "PLAYERS_NOT_READY") return t.playersNotReady;
  if (["HOST_ONLY", "NOT_HOST"].includes(code)) return t.hostOnly;
  if (code === "NOT_YOUR_TURN") return t.notTurn;
  if (code === "RETURN_TO_LOBBY_FIRST") return locale === "zh-CN" ? "已有玩家返回房间，请返回后重新准备。" : locale === "fr" ? "Un joueur retourne à la salle. Revenez pour vous préparer." : "A player is returning to the room. Return and get ready again.";
  if (["STALE_HAND", "STALE_COMMAND", "STALE_ROUND", "STALE_TURN", "DEADLINE_EXPIRED", "WRONG_PHASE"].includes(code)) return t.stale;
  return t.error;
}
export function unoEventLabel(event: UnoEvent, state: UnoViewerState, locale: string) {
  const t = getUnoCopy(locale);
  const name = state.players.find(p => p.seat === event.seat)?.name ?? "";
  switch (event.kind) {
    case "DEAL": return t.dealt;
    case "PLAY": return `${name} ${t.played} ${event.card ? unoCardLabel(event.card, locale) : ""}`;
    case "DRAW": return `${name} ${t.drew} ${event.count ?? 1} ${unoCardUnit(event.count ?? 1, locale)}`;
    case "PASS": return `${name} ${t.passed}`;
    case "UNO": return `${name} · UNO!`;
    case "CAUGHT": return `${state.players.find(p => p.seat === event.targetSeat)?.name ?? name} ${t.caught}`;
    case "FALSE_CATCH": return `${name} ${t.falseCatch}`;
    case "CHALLENGE_WON": return `${name} ${t.challengeWon}`;
    case "CHALLENGE_LOST": return `${name} ${t.challengeLost}`;
    case "ACCEPT_DRAW_FOUR": return `${name} ${t.accepted}`;
    case "COLOR": return `${name} ${t.chose} ${event.color ? t[event.color] : ""}`;
    case "ROUND_WIN": return `${name} ${t.roundWin}`;
    case "TIMEOUT": return `${name} ${t.timeout} · ${event.count ? `${t.drew} ${event.count} ${unoCardUnit(event.count, locale)}` : t.passed}`;
  }
}
