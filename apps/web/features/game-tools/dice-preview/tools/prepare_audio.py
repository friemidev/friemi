"""Prepare recorded CC0 dice foley: python3 prepare_audio.py SOURCE_DIR OUTPUT_DIR.

SOURCE_DIR contains 2bach-{id}.mp3 HQ public previews from Freesound's
Dice sounds (yatzy style) pack. Requires ffmpeg; no generated audio is used.
Writes the MP3, source credits and matching runtime metadata together.
"""
import array
import hashlib
import json
from pathlib import Path
import subprocess
import sys

source, output = map(Path, sys.argv[1:3])
output.mkdir(parents=True, exist_ok=True)
runtime = Path(__file__).resolve().parent.parent / "runtime"
rate = 44100
# End times retain the recording's final collisions and short room decay.
takes = {
    "1": {
        "shake": (185968, [1.62, 4.45, 7.25], 1.4),
        "covered": (185962, [(0.04, 1.35), (3.00, 4.45), (5.57, 7.15)], None),
        "landing": (185963, [(0.10, .56), (4.44, 4.94), (10.13, 10.68)], None),
    },
    "3": {
        "shake": (185978, [2.06, 5.85, 8.75], 1.4),
        "covered": (185980, [1.96, 5.01, 8.42], 1.8),
        "landing": (185970, [(0, .65), (3.28, 3.84), (4.65, 5.35)], None),
    },
    "6": {
        "shake": (185972, [2.59, 6.07, 9.35], 1.4),
        "covered": (185974, [(0.12, 1.87), (2.95, 4.75), (8.99, 10.79)], None),
        "landing": (185982, [(.04, .66), (3.68, 4.44), (7.76, 8.43)], None),
    },
}
names = {
    185968: "Dice (1) shake in cup.wav", 185962: "Dice (1) shake in cup closed.wav",
    185963: "Dice (1) pour on felt.wav", 185978: "Dice (3) shake in cup.wav",
    185980: "Dice (3) shake in cup closed.wav", 185970: "Dice (3) pour on felt.wav",
    185972: "Dice (6) shake in cup.wav", 185974: "Dice (6) shake in cup closed.wav",
    185982: "Dice (6) pour on felt.wav",
}
recordings = {}
for ident in names:
    data = subprocess.check_output([
        "ffmpeg", "-hide_banner", "-loglevel", "error", "-i", str(source / f"2bach-{ident}.mp3"),
        "-ac", "1", "-ar", str(rate), "-af", "highpass=f=65", "-f", "s16le", "pipe:1",
    ])
    pcm = array.array("h", data)
    # One gain adjustment per original recording, never per collision/take.
    scale = .78 * 32767 / max(1, max(map(abs, pcm)))
    recordings[ident] = array.array("h", (round(value * scale) for value in pcm))

atlas = array.array("h")
pools = {}
def append(ident, start, end):
    pcm = recordings[ident][round(start * rate):round(end * rate)]
    # Feather only the cut edges; preserve attacks and decay between them.
    for n in range(min(round(.003 * rate), len(pcm))):
        pcm[n] = round(pcm[n] * n / (.003 * rate))
    for n in range(min(round(.012 * rate), len(pcm))):
        pcm[-n-1] = round(pcm[-n-1] * n / (.012 * rate))
    sprite = {"offset": round(len(atlas) / rate, 5), "duration": round(len(pcm) / rate, 5)}
    atlas.extend(pcm)
    atlas.extend([0] * round(.07 * rate))
    return sprite

for group, kinds in takes.items():
    pools[group] = {}
    for kind, (ident, ranges, length) in kinds.items():
        ranges = [(end - length, end) for end in ranges] if length else ranges
        pools[group][kind] = [append(ident, start, end) for start, end in ranges]
        if kind == "covered":
            ticks = []
            for start, end in ranges:
                # Locate a real late cup collision for the reduced-motion cue.
                tail_start = round((end - .5) * rate)
                tail_end = round((end - .12) * rate)
                pcm = recordings[ident]
                peak = max(range(tail_start, tail_end), key=lambda n: abs(pcm[n])) / rate
                ticks.append(append(ident, max(start, peak - .012), min(end, peak + .208)))
            pools[group]["closedTick"] = ticks

raw = atlas.tobytes()
version = hashlib.sha256(raw).hexdigest()[:10]
filename = f"dice-foley-{version}.mp3"
subprocess.run([
    "ffmpeg", "-hide_banner", "-loglevel", "error", "-f", "s16le", "-ar", str(rate),
    "-ac", "1", "-i", "pipe:0", "-c:a", "libmp3lame", "-b:a", "160k",
    "-metadata", "comment=2BACH CC0 physical dice foley; see LICENSE.md", "-y", str(output / filename),
], input=raw, check=True)
metadata = {"url": f"/sounds/dice/{filename}", "duration": round(len(atlas) / rate, 5), "groups": pools}
(runtime / "dice-audio-data.js").write_text(
    "// Generated by tools/prepare_audio.py. Keep offsets and the content-versioned asset together.\n"
    + "export const diceAudioData = " + json.dumps(metadata, indent=2) + ";\n"
)
credits = [
    "# Dice audio sources", "",
    f"`{filename}` contains excerpts from **2BACH — Dice sounds (yatzy style)**.",
    "Pack: https://freesound.org/people/2BACH/packs/11753/", "",
    "The author recorded the set with a Sennheiser MKH 416 and Focusrite Scarlett",
    "2i2, at 48 kHz / 24 bit. We use the public HQ MP3 previews, not the original WAVs.",
    "All nine source sounds are licensed CC0 1.0:",
    "https://creativecommons.org/publicdomain/zero/1.0/", "",
]
for ident, name in names.items():
    digest = hashlib.sha256((source / f"2bach-{ident}.mp3").read_bytes()).hexdigest()
    credits.extend([
        f"- **{name}** — https://freesound.org/people/2BACH/sounds/{ident}/",
        f"  Preview: https://cdn.freesound.org/previews/185/{ident}_878622-hq.mp3",
        f"  SHA256: `{digest}`.",
    ])
credits.extend([
    "", "Preparation: mono 44.1 kHz, 65 Hz rumble removal, one gain adjustment per",
    "source recording, trimmed takes and short edge fades. No synthesized impacts,",
    "pitch changes, dynamic-range compression or added reverb. The 1-, 3- and 6-die recordings",
    "serve the UI's 1, 2–3 and 4–6 count groups respectively. Closed-cup recordings",
    "include their own settling; they never use the open-cup felt landing.",
    "The reproducible script is `features/game-tools/dice-preview/tools/prepare_audio.py`.",
])
(output / "LICENSE.md").write_text("\n".join(credits) + "\n")
print(json.dumps({"file": filename, "bytes": (output / filename).stat().st_size, "duration": metadata["duration"]}))
